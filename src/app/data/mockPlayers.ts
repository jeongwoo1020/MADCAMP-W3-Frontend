// 연봉 계산 함수 (OPS 또는 ERA 기반)
function calculateSalary(player: Omit<Player, 'salary'>): number {
  if (player.position === '투수') {
    const era = player.stats.era || 4.5;
    // ERA가 낮을수록 높은 연봉 (1.5 ~ 6.0 범위)
    const salaryBase = Math.max(10, Math.min(100, (6.0 - era) * 20));
    // 역할에 따른 가중치
    const roleMultiplier =
      player.pitcherRole === 'starter' ? 1.5 :
        player.pitcherRole === 'closer' ? 1.3 :
          1.0;
    return Math.round(salaryBase * roleMultiplier);
  } else {
    const ops = player.stats.ops || 0.7;
    // OPS가 높을수록 높은 연봉 (0.6 ~ 1.0 범위)
    const salaryBase = Math.max(10, Math.min(100, (ops - 0.6) * 200));
    return Math.round(salaryBase);
  }
}

